// Package local owns private paths, credentials and the daemon's lifetime lock.
package local

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"io"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"syscall"
)

// Paths holds independent local storage and credential locations.
type Paths struct{ DataDir, TokenFile string }

// Resolve applies XDG defaults without consulting the working directory.
func Resolve(dataDir, tokenFile string) (Paths, error) {
	home, err := os.UserHomeDir()
	if err != nil && (dataDir == "" && os.Getenv("XDG_DATA_HOME") == "" || tokenFile == "" && os.Getenv("XDG_CONFIG_HOME") == "") {
		return Paths{}, errors.New("home directory unavailable")
	}
	if dataDir == "" {
		base := os.Getenv("XDG_DATA_HOME")
		if base == "" {
			base = filepath.Join(home, ".local", "share")
		}
		dataDir = filepath.Join(base, "artel", "v2")
	}
	if tokenFile == "" {
		base := os.Getenv("XDG_CONFIG_HOME")
		if base == "" {
			base = filepath.Join(home, ".config")
		}
		tokenFile = filepath.Join(base, "artel", "local-owner.token")
	}
	if !filepath.IsAbs(dataDir) || !filepath.IsAbs(tokenFile) {
		return Paths{}, errors.New("local paths must be absolute")
	}
	return Paths{filepath.Clean(dataDir), filepath.Clean(tokenFile)}, nil
}

func noSymlinks(path string) error {
	for p := filepath.Clean(path); ; p = filepath.Dir(p) {
		info, err := os.Lstat(p)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return errors.New("cannot inspect local path")
		}
		if err == nil && info.Mode()&os.ModeSymlink != 0 {
			return errors.New("symlink local path rejected")
		}
		if p == filepath.Dir(p) {
			return nil
		}
	}
}

func privateInfo(info os.FileInfo, dir bool) error {
	stat, ok := info.Sys().(*syscall.Stat_t)
	expected := os.FileMode(0o600)
	if dir {
		expected = 0o700
	}
	if !ok || int64(stat.Uid) != int64(os.Getuid()) || info.Mode().Perm() != expected || info.Mode()&(os.ModeSetuid|os.ModeSetgid|os.ModeSticky) != 0 || info.IsDir() != dir || !dir && !info.Mode().IsRegular() {
		return errors.New("unsafe local ownership or permissions")
	}
	return nil
}

func privateDir(path string) error {
	if err := noSymlinks(path); err != nil {
		return err
	}
	if err := os.MkdirAll(path, 0o700); err != nil {
		return errors.New("cannot create private directory")
	}
	info, err := os.Lstat(path)
	if err != nil {
		return errors.New("cannot inspect private directory")
	}
	return privateInfo(info, true)
}

// ReadToken refuses symlinks and unsafe files before reading any credential.
func ReadToken(path string) (string, error) {
	if !filepath.IsAbs(path) || filepath.Clean(path) != path {
		return "", errors.New("credential path must be absolute")
	}
	if err := noSymlinks(path); err != nil {
		return "", err
	}
	parent, err := os.Stat(filepath.Dir(path))
	if err != nil {
		return "", errors.New("credential directory unavailable")
	}
	if err = privateInfo(parent, true); err != nil {
		return "", err
	}
	// O_NOFOLLOW prevents replacement of the final component with a symlink.
	fd, err := syscall.Open(path, syscall.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_CLOEXEC|syscall.O_NONBLOCK, 0)
	if err != nil {
		return "", errors.New("credential unavailable")
	}
	// #nosec G115 -- Successful syscall.Open returns a nonnegative descriptor.
	f := os.NewFile(uintptr(fd), "credential")
	defer func() { _ = f.Close() }()
	info, err := f.Stat()
	if err != nil {
		return "", errors.New("credential unavailable")
	}
	if err = privateInfo(info, false); err != nil {
		return "", err
	}
	if info.Size() != 65 {
		return "", errors.New("invalid credential format")
	}
	buf := make([]byte, 65)
	n, err := io.ReadFull(f, buf)
	if err != nil || n != len(buf) {
		return "", errors.New("credential read failed")
	}
	token := string(buf[:64])
	decoded, err := hex.DecodeString(token)
	if err != nil || len(decoded) != 32 || buf[64] != '\n' {
		return "", errors.New("invalid credential format")
	}
	return token, nil
}

// InitToken atomically publishes a complete credential and never replaces one.
func InitToken(path string) (string, error) {
	if !filepath.IsAbs(path) || filepath.Clean(path) != path {
		return "", errors.New("credential path must be absolute")
	}
	if err := privateDir(filepath.Dir(path)); err != nil {
		return "", err
	}
	if _, err := os.Lstat(path); err == nil {
		return ReadToken(path)
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", errors.New("credential unavailable")
	}
	bytes := make([]byte, 32)
	if _, err := rand.Read(bytes); err != nil {
		return "", errors.New("credential generation failed")
	}
	token := hex.EncodeToString(bytes)
	f, err := os.CreateTemp(filepath.Dir(path), ".owner-*")
	if err != nil {
		return "", errors.New("credential creation failed")
	}
	// #nosec G703 -- Name is generated by CreateTemp in the validated private directory.
	defer func() { _ = os.Remove(f.Name()) }()
	if _, err = f.WriteString(token + "\n"); err == nil {
		err = f.Sync()
	}
	closeErr := f.Close()
	if err != nil || closeErr != nil {
		return "", errors.New("credential write failed")
	}
	if err = os.Link(f.Name(), path); err != nil && !errors.Is(err, os.ErrExist) {
		return "", errors.New("credential publication failed")
	}
	dir, err := os.Open(filepath.Dir(path))
	if err != nil {
		return "", errors.New("credential directory unavailable")
	}
	syncErr := dir.Sync()
	_ = dir.Close()
	if syncErr != nil {
		return "", errors.New("credential directory sync failed")
	}
	return ReadToken(path)
}

// Lock is held for the entire daemon lifetime. The lock file is never unlinked.
type Lock struct{ file *os.File }

// Acquire refuses a second daemon using the same data directory.
func Acquire(dir string) (*Lock, error) { return acquire(dir, "daemon.lock") }

func acquire(dir, name string) (*Lock, error) {
	if !filepath.IsAbs(dir) {
		return nil, errors.New("data directory must be absolute")
	}
	if err := privateDir(dir); err != nil {
		return nil, err
	}
	path := filepath.Join(dir, name)
	fd, err := syscall.Open(path, syscall.O_RDWR|syscall.O_CREAT|syscall.O_NOFOLLOW|syscall.O_CLOEXEC, 0o600)
	if err != nil {
		return nil, errors.New("cannot open daemon lock")
	}
	// #nosec G115 -- Successful syscall.Open returns a nonnegative descriptor.
	f := os.NewFile(uintptr(fd), "daemon lock")
	info, err := f.Stat()
	if err == nil {
		err = privateInfo(info, false)
	}
	if err == nil {
		err = syscall.Flock(fd, syscall.LOCK_EX|syscall.LOCK_NB)
	}
	if err != nil {
		_ = f.Close()
		return nil, errors.New("data directory locked or unsafe")
	}
	return &Lock{f}, nil
}

// Close releases the lifetime lock.
func (l *Lock) Close() error { return l.file.Close() }

// ListenAddress validates a numeric IPv4 loopback bind, including ephemeral port 0.
func ListenAddress(address string) error {
	host, port, err := net.SplitHostPort(address)
	if err != nil || host != "127.0.0.1" {
		return errors.New("listen address must be 127.0.0.1:<port>")
	}
	n, err := strconv.Atoi(port)
	if err != nil || n < 0 || n > 65535 || strconv.Itoa(n) != port {
		return errors.New("invalid local port")
	}
	return nil
}

// Endpoint validates a credential-safe HTTP API endpoint without URL credentials.
func Endpoint(endpoint string) error {
	u, err := url.Parse(endpoint)
	if err != nil {
		return errors.New("invalid endpoint")
	}
	if u.Scheme != "http" || u.User != nil || u.Path != "" || u.RawQuery != "" || u.Fragment != "" || strings.Contains(endpoint, "?") {
		return errors.New("endpoint must be http://127.0.0.1:<port>")
	}
	if err = ListenAddress(u.Host); err != nil {
		return err
	}
	if u.Port() == "0" {
		return errors.New("endpoint port must be nonzero")
	}
	return nil
}
